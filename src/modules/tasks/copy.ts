import type { tasks } from './schema';

type TaskRow = typeof tasks.$inferSelect;

/** What a copy of a task never takes from its source: who it is, when it happened, and what belonged to that one post. */
export type TaskCopyFields = Omit<
  TaskRow,
  | 'id'
  | 'slug'
  | 'createdAt'
  | 'updatedAt'
  | 'publishedAt'
  | 'expiresAt'
  | 'aiGenerationId'
  | 'reopenedAt'
  | 'hiddenAt'
  | 'hiddenByUserId'
  | 'hiddenReason'
  | 'requestKey'
  | 'searchText'
  | 'teamPartOf'
>;

/**
 * The columns a new task copies from an earlier one: Book again, a helper's rebooking proposal, a regular visit and
 * a team partner's part all start from a past task (sweep 2026-11-24, M1). The copy is a new post, so it leaves out
 * the source's identity and timestamps, its staff hiding, its reopening, and two things that are unique to the
 * source: its request key (a client's double-tap guard, unique per client, so a copy carrying it failed every Book
 * again and rebooking of a task posted through the wizard) and its team part (a copy of a partner's part is the
 * client's own task, not part of that team). The search text is generated by the database.
 */
export function taskCopyFields(task: TaskRow): TaskCopyFields {
  const {
    id: _id,
    slug: _slug,
    createdAt: _created,
    updatedAt: _updated,
    publishedAt: _published,
    expiresAt: _expires,
    aiGenerationId: _ai,
    reopenedAt: _reopened,
    hiddenAt: _hidden,
    hiddenByUserId: _hiddenBy,
    hiddenReason: _hiddenReason,
    requestKey: _requestKey,
    searchText: _searchText,
    teamPartOf: _teamPartOf,
    ...copy
  } = task;
  return copy;
}
